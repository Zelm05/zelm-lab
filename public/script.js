const SETTINGS_VERSION = 4;

let settings = { ...DEFAULT_SETTINGS };
try {
  const saved = JSON.parse(localStorage.getItem('zelm_settings'));
  if (saved) {
    const merged = { ...DEFAULT_SETTINGS, ...saved };
    merged.games = { ...DEFAULT_SETTINGS.games, ...(saved.games || {}) };
    merged.__v = SETTINGS_VERSION;
    settings = merged;
    localStorage.setItem('zelm_settings', JSON.stringify(settings));
  }
} catch { /* 忽略损坏数据 */ }

function saveSettings() {
  try { localStorage.setItem('zelm_settings', JSON.stringify(settings)); } catch { /* 忽略 */ }
}

/* 跨标签页同步：其他标签页修改设置（主题/语言等）时本页即时生效 */
window.addEventListener('storage', (e) => {
  if (e.key !== 'zelm_settings' || !e.newValue) return;
  try {
    const saved = JSON.parse(e.newValue);
    const merged = { ...DEFAULT_SETTINGS, ...saved };
    merged.games = { ...DEFAULT_SETTINGS.games, ...(saved.games || {}) };
    const langChanged = merged.lang !== settings.lang;
    settings = merged;
    applySettings();          // 主题等其余设置
    if (langChanged) { applyLang(); try { document.dispatchEvent(new CustomEvent('zelm:lang', { detail: { lang: settings.lang } })); } catch (e) {} } // 语言（含资源/社区模块重渲染）
  } catch { /* 忽略损坏数据 */ }
});

